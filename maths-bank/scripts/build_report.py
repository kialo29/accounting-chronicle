"""Compile reports/verification.md from the per-topic checker/diagram logs in reports/parts/,
plus bank statistics (counts per strand, difficulty and type) and the validator result.

   python3 scripts/build_report.py
"""
import json, pathlib, re, subprocess, sys
from collections import Counter, defaultdict

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import skeleton  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
TYPES = ["fluency", "reasoning", "problem-solving", "spot-the-mistake", "exam-style", "real-world", "synoptic"]


def load_questions():
    qs = []
    for f in sorted((ROOT / "data" / "questions").glob("*.json")):
        qs += json.loads(f.read_text())
    return qs


def main():
    topics = json.loads((ROOT / "data" / "topics.json").read_text())["topics"]
    tby = {t["id"]: t for t in topics}
    qs = load_questions()
    strands = [s for s in skeleton.STRANDS.values()]

    by_strand = Counter(tby[q["topicId"]]["strand"] for q in qs)
    by_diff = Counter(q["difficulty"] for q in qs)
    by_type = Counter(q["type"] for q in qs)
    strand_diff = defaultdict(Counter)
    for q in qs:
        strand_diff[tby[q["topicId"]]["strand"]][q["difficulty"]] += 1
    topics_by_strand = Counter(t["strand"] for t in topics)
    diagrams = sum(1 for q in qs if q.get("diagram"))
    marks = sum(q.get("marks", 0) for q in qs)

    # checker logs
    tot = Counter()
    rows = []  # (topic, question, result, note)
    diag = Counter()
    topic_fixes = []
    missing = []
    for t in topics:
        f = ROOT / "reports" / "parts" / f"{t['id']}.md"
        if not f.exists():
            missing.append(t["id"])
            continue
        text = f.read_text()
        m = re.search(r"Checked (\d+) questions?: (\d+) ok, (\d+) fixed, (\d+) clarified", text)
        if m:
            n, a, b, c = map(int, m.groups())
            tot.update(checked=n, ok=a, fixed=b, clarified=c, topics=1)
        else:
            missing.append(t["id"] + " (no summary line)")
        tm = re.search(r"Topic details:\s*(.+)", text)
        if tm and not tm.group(1).strip().lower().startswith("ok"):
            topic_fixes.append((t["id"], tm.group(1).strip()))
        for line in text.splitlines():
            r = re.match(r"\|\s*([a-z0-9-]+-q\d\d)\s*\|\s*(fixed|clarified)\s*\|\s*(.+?)\s*\|\s*$", line)
            if r:
                rows.append((t["id"], r.group(1), r.group(2), r.group(3)))
        for dm in re.finditer(r"(\d+) diagrams? checked[^:\n]*: (\d+) ok(?:, (\d+) (?:fixed|changed))?", text):
            n, a = int(dm.group(1)), int(dm.group(2))
            diag.update(checked=n, ok=a, fixed=int(dm.group(3) or 0), topics=1)

    val = subprocess.run(["node", str(ROOT / "scripts" / "validate.mjs"), "--quiet"], capture_output=True, text=True)
    vline = val.stdout.strip().splitlines()[-1] if val.stdout.strip() else val.stderr.strip()

    L = []
    L.append("# Verification report\n")
    L.append("Learn With Kian maths question bank. Generated by `scripts/build_report.py` from the per-topic logs in "
             "`reports/parts/`.\n")
    L.append("## How the bank was verified\n")
    L.append("1. **Schema and integrity validation** (`node scripts/validate.mjs`): required fields and types, unique ids, "
             "every prerequisite / linked topic / misconception id exists, prerequisite graph is acyclic, `$…$`/`$$…$$` "
             "delimiters balance, every maths span parses in KaTeX, no LaTeX outside maths, no JSON escape damage, SVG "
             "diagrams are well-formed and safe, markdown tables are rectangular, and every topic has 15–20 questions, all "
             "5 difficulties, ≥4 question types, ≥2 synoptic questions, ≥1 exam-style question, a variation-theory "
             "sequence and every misconception targeted.")
    L.append("2. **Independent blind checking**: a separate checker agent (never the writer) printed each topic's questions "
             "without hints/answers (`scripts/blind.mjs`), solved every question itself (with sympy/scipy for numerical "
             "and statistical work), and only then compared with the stored answer and worked solution. Mismatches were "
             "fixed; ambiguous questions were reworded so there is exactly one intended answer. The checker also verified "
             "each topic's worked examples and misconceptions and rendered every diagram to PNG to look at it.")
    L.append("3. **Diagram audit**: a third pass by separate agents rendered every SVG diagram and checked it against the "
             "question text and answer (values, scales, grid alignment, proportions, legibility, no give-aways).")
    L.append("4. **Browser smoke test** (`node scripts/smoke-test.mjs`): loads the app in headless Chromium at desktop and "
             "phone widths in light and dark mode, exercises search, filters, topic pages, reveals, learning paths and "
             "the worksheet builder, prints worksheet and answer-sheet PDFs, and renders every formula in the bank "
             "through KaTeX in the browser.\n")
    L.append("## Result\n")
    L.append(f"* Validator: `{vline}`")
    L.append(f"* Questions independently checked: **{tot['checked']}** across {tot['topics']} topics — "
             f"{tot['ok']} correct as written, **{tot['fixed']} fixed** (wrong answer/solution/marks/diagram), "
             f"**{tot['clarified']} clarified** (reworded for a single unambiguous answer, or relabelled).")
    if diag["checked"]:
        L.append(f"* Diagram audit: {diag['checked']} diagrams in {diag['topics']} topics — {diag['ok']} ok, "
                 f"**{diag['fixed']} fixed**.")
    L.append(f"* Topic-detail corrections (worked examples / misconceptions / key ideas): {len(topic_fixes)}")
    if missing:
        L.append(f"* Topics without a checker log: {len(missing)} — {', '.join(missing)}")
    L.append("")
    L.append("## Bank statistics\n")
    L.append(f"{len(topics)} topics · {len(qs)} questions · {diagrams} SVG diagrams · {by_type['exam-style']} exam-style "
             f"questions carrying {marks} marks\n")
    L.append("| Strand | Topics | Questions | D1 | D2 | D3 | D4 | D5 |")
    L.append("|---|---:|---:|---:|---:|---:|---:|---:|")
    for s in strands:
        d = strand_diff[s]
        L.append(f"| {s} | {topics_by_strand[s]} | {by_strand[s]} | " + " | ".join(str(d[i]) for i in range(1, 6)) + " |")
    L.append(f"| **Total** | **{len(topics)}** | **{len(qs)}** | " + " | ".join(f"**{by_diff[i]}**" for i in range(1, 6)) + " |\n")
    L.append("| Type | Questions |")
    L.append("|---|---:|")
    for t in TYPES:
        L.append(f"| {t} | {by_type[t]} |")
    L.append("")
    if topic_fixes:
        L.append("## Topic-detail corrections\n")
        for tid, note in topic_fixes:
            L.append(f"* `{tid}`: {note}")
        L.append("")
    L.append("## Every fixed or clarified question\n")
    L.append("| Topic | Question | Result | What changed |")
    L.append("|---|---|---|---|")
    for tid, qid, res, note in rows:
        L.append(f"| {tid} | {qid} | {res} | {note} |")
    L.append("")
    L.append("## Per-topic logs\n")
    L.append("Full logs, including the diagram audit notes, are in `reports/parts/<topicId>.md`.")
    (ROOT / "reports" / "verification.md").write_text("\n".join(L) + "\n")
    print(f"wrote reports/verification.md: {tot['checked']} checked, {tot['fixed']} fixed, {tot['clarified']} clarified, "
          f"{len(rows)} detail rows, diagrams {dict(diag)}, missing {len(missing)}")


if __name__ == "__main__":
    main()
